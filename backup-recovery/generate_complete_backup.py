"""
AutoInspect AI - Complete PostgreSQL SQL Logical Export Generator (`pg_catalog`).

Generates a single-file, self-contained logical SQL export (`autoinspect_complete_backup.sql`)
and inventory manifest (`autoinspect_complete_backup_manifest.json`) from live PostgreSQL
catalog introspection (`pg_catalog`). This logical SQL export is distinct from binary custom
archives generated by `pg_dump --format=custom`.

Includes:
- Guarded extension & schema creation plus explicit `search_path = public, extensions, pg_catalog`
- Sequences (properties, OWNED BY bindings, and exact setval() cursor states)
- All tables in public schema (exact types, precision, IDENTITY columns, defaults)
- Primary Keys & Unique Constraints (Pre-Data)
- Complete DML INSERT statements for all rows with deterministic PK / ctid ordering
- Check Constraints (preserving NOT VALID flags)
- Foreign Keys (including guarded external-schema references to auth.users)
- All standalone & constraint-backing indexes (explicitly itemized in manifest)
- User-defined Functions, Function ACLs (`proacl`, incl. `REVOKE ALL FROM PUBLIC`), and Triggers
  (also recording external `auth` schema triggers calling public functions in comments/manifest)
- Row Level Security (RLS) enablement, Policies (with Supabase auth portability guards & visible
  `SET client_min_messages = notice;` portability warnings), Schema ACLs, Table ACLs (`MAINTAIN`
  supported via `aclexplode`), & Sequence ACLs

Strictly READ-ONLY against the source database.
"""

import sys as _sys
from pathlib import Path as _Path
_MODELS_DIR = _Path(__file__).resolve().parent.parent / 'models'
if str(_MODELS_DIR) not in _sys.path:
    _sys.path.insert(0, str(_MODELS_DIR))

import json
import uuid
from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any, List

from sqlalchemy import create_engine, text
from app.config import settings

BACKEND_DIR = Path(__file__).resolve().parent
OUTPUT_SQL_PATH = BACKEND_DIR / "autoinspect_complete_backup.sql"
OUTPUT_MANIFEST_PATH = BACKEND_DIR / "autoinspect_complete_backup_manifest.json"

CORE_TABLE_ORDER = [
    "users",
    "profiles",
    "vehicles",
    "inspections",
    "damage_detections",
    "detected_damages",
    "detections",
    "reports",
    "regions",
    "id",
]


def quote_ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def pg_literal(val: Any) -> str:
    """Formats a Python value safely as a native PostgreSQL SQL literal."""
    if val is None:
        return "NULL"
    if isinstance(val, bool):
        return "TRUE" if val else "FALSE"
    if isinstance(val, (int, float, Decimal)):
        return str(val)
    if isinstance(val, uuid.UUID):
        return f"'{val}'::uuid"
    if isinstance(val, datetime):
        return f"'{val.isoformat()}'"
    if isinstance(val, (dict, list)):
        json_str = json.dumps(val, ensure_ascii=False)
        if "\n" in json_str or "\r" in json_str or "\x00" in json_str:
            escaped = (
                json_str.replace("\x00", "")
                .replace("\\", "\\\\")
                .replace("'", "''")
                .replace("\n", "\\n")
                .replace("\r", "\\r")
            )
            return f"E'{escaped}'::jsonb"
        return "'" + json_str.replace("'", "''") + "'::jsonb"

    s = str(val)
    if "\n" in s or "\r" in s or "\x00" in s:
        escaped = (
            s.replace("\x00", "")
            .replace("\\", "\\\\")
            .replace("'", "''")
            .replace("\n", "\\n")
            .replace("\r", "\\r")
        )
        return f"E'{escaped}'"
    return "'" + s.replace("'", "''") + "'"


def generate_complete_backup() -> None:
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    engine = create_engine(settings.DATABASE_URL)

    lines: List[str] = []
    manifest = {
        "generated_at_utc": timestamp,
        "backup_file": OUTPUT_SQL_PATH.name,
        "format": "PostgreSQL complete single-file SQL logical export (pg_catalog-generated; not pg_dump -Fc archive)",
        "generation_method": "pg_catalog logical SQL export (psycopg 3)",
        "tables_count": 0,
        "total_rows": 0,
        "tables": {},
        "sequences_count": 0,
        "sequences": {},
        "constraints": {
            "total": 0,
            "primary_and_unique": 0,
            "check": 0,
            "foreign_key_public": 0,
            "foreign_key_external": 0,
        },
        "indexes": {
            "total_pg_indexes": 0,
            "constraint_backing": 0,
            "standalone": 0,
        },
        "functions": {
            "public_user_defined": 0,
            "revoked_from_public": 0,
        },
        "triggers": {
            "public_schema": 0,
            "external_schema_referencing_public": [],
        },
        "policies": {
            "total": 0,
            "auth_dependent_guarded": 0,
            "non_auth": 0,
        },
    }

    with engine.connect() as conn:
        pg_version = conn.execute(text("SELECT version();")).scalar()
        source_db = conn.execute(text("SELECT current_database();")).scalar()

        # Discover extensions used by public defaults/UUID generation
        ext_rows = conn.execute(
            text("""
                SELECT e.extname, n.nspname
                FROM pg_extension e
                JOIN pg_namespace n ON n.oid = e.extnamespace
                WHERE e.extname IN ('pgcrypto', 'uuid-ossp')
                ORDER BY e.extname;
            """)
        ).fetchall()

        # Discover external triggers (e.g. auth.users) calling functions defined in public
        ext_triggers = conn.execute(
            text("""
                SELECT n.nspname, c.relname, t.tgname, p.proname
                FROM pg_trigger t
                JOIN pg_class c ON c.oid = t.tgrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                JOIN pg_proc p ON p.oid = t.tgfoid
                JOIN pg_namespace pn ON pn.oid = p.pronamespace
                WHERE NOT t.tgisinternal
                  AND n.nspname <> 'public'
                  AND pn.nspname = 'public'
                ORDER BY n.nspname, c.relname, t.tgname;
            """)
        ).fetchall()
        manifest["triggers"]["external_schema_referencing_public"] = [
            f"{s}.{t}:{tg}->{fn}()" for s, t, tg, fn in ext_triggers
        ]

        lines.extend([
            "-- ==========================================================================",
            "-- AUTOINSPECT AI - COMPLETE POSTGRESQL LOGICAL SQL EXPORT",
            f"-- Generated at: {timestamp}",
            f"-- Source Database: {source_db} ({pg_version})",
            "-- Format: pg_catalog logical SQL script (distinct from pg_dump -Fc archive)",
            "-- ==========================================================================",
            "",
            "SET statement_timeout = 0;",
            "SET lock_timeout = 0;",
            "SET idle_in_transaction_session_timeout = 0;",
            "SET client_encoding = 'UTF8';",
            "SET standard_conforming_strings = on;",
            "SET check_function_bodies = false;",
            "SET xmloption = content;",
            "SET client_min_messages = notice;",
            "SET row_security = off;",
            "SET search_path = public, extensions;",
            "",
            "BEGIN;",
            "",
            "-- --------------------------------------------------------------------------",
            "-- 1. EXTENSIONS & SCHEMA SAFETY",
            "-- --------------------------------------------------------------------------",
        ])

        ext_list = ext_rows or [("pgcrypto", "extensions"), ("uuid-ossp", "extensions")]
        created_schemas = set()
        for ext_name, ext_schema in ext_list:
            if ext_schema != "public" and ext_schema not in created_schemas:
                lines.append(f"CREATE SCHEMA IF NOT EXISTS {quote_ident(ext_schema)};")
                created_schemas.add(ext_schema)
            lines.extend([
                "DO $$ BEGIN",
                f"    CREATE EXTENSION IF NOT EXISTS {quote_ident(ext_name)} WITH SCHEMA {quote_ident(ext_schema)};",
                "EXCEPTION WHEN OTHERS THEN",
                f"    RAISE NOTICE 'Extension {ext_name} (schema {ext_schema}) portability notice: %', SQLERRM;",
                "END $$;",
            ])
        lines.append("")

        # Discover all public tables, core first then chronological/alphabetical
        all_tables_raw = [
            r[0]
            for r in conn.execute(
                text("SELECT tablename FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename;")
            ).fetchall()
        ]
        ordered_tables = [t for t in CORE_TABLE_ORDER if t in all_tables_raw] + [
            t for t in all_tables_raw if t not in CORE_TABLE_ORDER
        ]
        manifest["tables_count"] = len(ordered_tables)

        # ----------------------------------------------------------------------
        # 2. SEQUENCES (Exclude internal IDENTITY sequences owned with deptype='i')
        # ----------------------------------------------------------------------
        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 2. SEQUENCES (PRE-DATA)",
            "-- --------------------------------------------------------------------------",
        ])

        seq_rows = conn.execute(
            text("""
                SELECT
                    s.sequencename,
                    s.data_type::text,
                    s.start_value,
                    s.min_value,
                    s.max_value,
                    s.increment_by,
                    s.cycle,
                    s.cache_size,
                    t_a.relname AS owned_table_a,
                    a_a.attname AS owned_col_a,
                    d_i.deptype AS identity_deptype
                FROM pg_sequences s
                JOIN pg_class c ON c.relname = s.sequencename AND c.relkind = 'S'
                JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = s.schemaname
                LEFT JOIN pg_depend d_a ON d_a.objid = c.oid AND d_a.deptype = 'a'
                LEFT JOIN pg_class t_a ON t_a.oid = d_a.refobjid
                LEFT JOIN pg_attribute a_a ON a_a.attrelid = t_a.oid AND a_a.attnum = d_a.refobjsubid
                LEFT JOIN pg_depend d_i ON d_i.objid = c.oid AND d_i.deptype = 'i'
                WHERE s.schemaname = 'public'
                ORDER BY s.sequencename;
            """)
        ).fetchall()

        owned_bindings = []
        all_seq_states = []

        for s in seq_rows:
            (
                seq_name,
                data_type,
                start_val,
                min_val,
                max_val,
                inc_by,
                is_cycle,
                cache_size,
                owned_tbl,
                owned_col,
                identity_dep,
            ) = s

            lv_row = conn.execute(
                text(f'SELECT last_value, is_called FROM public.{quote_ident(seq_name)};')
            ).fetchone()
            all_seq_states.append((seq_name, int(lv_row[0]), bool(lv_row[1])))
            manifest["sequences"][seq_name] = {
                "last_value": int(lv_row[0]),
                "is_called": bool(lv_row[1]),
                "owned_by": f"{owned_tbl}.{owned_col}" if owned_tbl else ("IDENTITY" if identity_dep == "i" else None),
            }

            if identity_dep == "i":
                # Created automatically by GENERATED ... AS IDENTITY column
                continue

            cycle_sql = "CYCLE" if is_cycle else "NO CYCLE"
            lines.append(
                f"CREATE SEQUENCE IF NOT EXISTS public.{quote_ident(seq_name)} "
                f"AS {data_type} "
                f"START WITH {start_val} "
                f"INCREMENT BY {inc_by} "
                f"MINVALUE {min_val} "
                f"MAXVALUE {max_val} "
                f"CACHE {cache_size} "
                f"{cycle_sql};"
            )
            if owned_tbl and owned_col:
                owned_bindings.append(
                    f"ALTER SEQUENCE public.{quote_ident(seq_name)} OWNED BY public.{quote_ident(owned_tbl)}.{quote_ident(owned_col)};"
                )
        manifest["sequences_count"] = len(all_seq_states)
        lines.append("")

        # ----------------------------------------------------------------------
        # 3. TABLES (ALL 22 TABLES IN PUBLIC SCHEMA)
        # ----------------------------------------------------------------------
        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 3. TABLES (PRE-DATA DDL)",
            "-- --------------------------------------------------------------------------",
        ])

        table_columns_map = {}

        for tbl in ordered_tables:
            cols = conn.execute(
                text("""
                    SELECT
                        a.attname,
                        pg_catalog.format_type(a.atttypid, a.atttypmod) AS col_type,
                        a.attnotnull,
                        pg_get_expr(ad.adbin, ad.adrelid) AS col_default,
                        a.attidentity::text
                    FROM pg_class c
                    JOIN pg_namespace n ON n.oid = c.relnamespace
                    JOIN pg_attribute a ON a.attrelid = c.oid
                    LEFT JOIN pg_attrdef ad ON ad.adrelid = c.oid AND ad.adnum = a.attnum
                    WHERE n.nspname = 'public'
                      AND c.relname = :t
                      AND a.attnum > 0
                      AND NOT a.attisdropped
                    ORDER BY a.attnum;
                """),
                {"t": tbl},
            ).fetchall()

            table_columns_map[tbl] = [c[0] for c in cols]
            col_lines = []
            for col_name, col_type, not_null, col_def, attidentity in cols:
                parts = [f"    {quote_ident(col_name)}", col_type]
                if attidentity == "d":
                    parts.append("GENERATED BY DEFAULT AS IDENTITY")
                elif attidentity == "a":
                    parts.append("GENERATED ALWAYS AS IDENTITY")
                elif col_def is not None:
                    parts.append(f"DEFAULT {col_def}")
                if not_null:
                    parts.append("NOT NULL")
                col_lines.append(" ".join(parts))

            lines.append(f"CREATE TABLE IF NOT EXISTS public.{quote_ident(tbl)} (")
            lines.append(",\n".join(col_lines))
            lines.append(");")
            lines.append("")

        if owned_bindings:
            lines.extend([
                "-- --------------------------------------------------------------------------",
                "-- 4. SEQUENCE OWNERSHIP BINDINGS",
                "-- --------------------------------------------------------------------------",
                *owned_bindings,
                "",
            ])

        # ----------------------------------------------------------------------
        # 5. PRIMARY KEYS & UNIQUE CONSTRAINTS (PRE-DATA)
        # ----------------------------------------------------------------------
        pk_cols_map = {
            r[0]: list(r[1])
            for r in conn.execute(
                text("""
                    SELECT c.relname, array_agg(a.attname ORDER BY u.ord)
                    FROM pg_constraint con
                    JOIN pg_class c ON c.oid = con.conrelid
                    JOIN pg_namespace n ON n.oid = c.relnamespace
                    CROSS JOIN LATERAL unnest(con.conkey) WITH ORDINALITY AS u(attnum, ord)
                    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = u.attnum
                    WHERE n.nspname = 'public' AND con.contype = 'p'
                    GROUP BY c.relname;
                """)
            ).fetchall()
        }

        pre_cons = conn.execute(
            text("""
                SELECT c.relname AS table_name,
                       con.conname,
                       pg_get_constraintdef(con.oid, true) AS condef
                FROM pg_constraint con
                JOIN pg_class c ON c.oid = con.conrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'public'
                  AND con.contype IN ('p', 'u')
                ORDER BY c.relname, con.contype DESC, con.conname;
            """)
        ).fetchall()

        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 5. PRIMARY KEY & UNIQUE CONSTRAINTS (PRE-DATA)",
            "-- --------------------------------------------------------------------------",
        ])
        for tbl_name, con_name, con_def in pre_cons:
            lines.append(
                f"ALTER TABLE ONLY public.{quote_ident(tbl_name)} "
                f"ADD CONSTRAINT {quote_ident(con_name)} {con_def};"
            )
            manifest["constraints"]["total"] += 1
            manifest["constraints"]["primary_and_unique"] += 1
        lines.append("")

        # ----------------------------------------------------------------------
        # 6. USER-DEFINED FUNCTIONS IN PUBLIC SCHEMA (Exclude Extension Functions)
        # ----------------------------------------------------------------------
        funcs = conn.execute(
            text("""
                SELECT
                    p.proname,
                    pg_catalog.pg_get_function_identity_arguments(p.oid) AS fn_args,
                    pg_get_functiondef(p.oid) AS fdef,
                    p.proacl IS NOT NULL AS has_acl,
                    EXISTS (
                        SELECT 1
                        FROM LATERAL aclexplode(COALESCE(p.proacl, ARRAY[]::aclitem[])) AS a
                        WHERE a.grantee = 0
                    ) AS public_has_exec
                FROM pg_proc p
                JOIN pg_namespace n ON n.oid = p.pronamespace
                WHERE n.nspname = 'public'
                  AND NOT EXISTS (
                      SELECT 1 FROM pg_depend d
                      WHERE d.objid = p.oid AND d.deptype = 'e'
                  )
                ORDER BY p.proname, fn_args;
            """)
        ).fetchall()

        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 6. FUNCTIONS IN PUBLIC SCHEMA",
            "-- --------------------------------------------------------------------------",
        ])
        for fname, fn_args, fdef, _, _ in funcs:
            clean_fdef = fdef.replace("\r\n", "\n").rstrip().rstrip(";") + ";"
            lines.append(clean_fdef)
            lines.append("")
            manifest["functions"]["public_user_defined"] += 1

        # ----------------------------------------------------------------------
        # 7. DATA RESTORATION (ALL TABLES WITH DETERMINISTIC ORDERING)
        # ----------------------------------------------------------------------
        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 7. TABLE DATA (DML INSERTS - DETERMINISTIC PK/CTID ORDERING)",
            "-- --------------------------------------------------------------------------",
        ])
        for tbl in ordered_tables:
            col_names = table_columns_map[tbl]
            col_list_sql = ", ".join(quote_ident(c) for c in col_names)
            pk_cols = pk_cols_map.get(tbl)
            order_sql = ", ".join(quote_ident(c) for c in pk_cols) if pk_cols else "ctid"
            rows = conn.execute(
                text(f"SELECT {col_list_sql} FROM public.{quote_ident(tbl)} ORDER BY {order_sql};")
            ).fetchall()
            manifest["tables"][tbl] = len(rows)
            manifest["total_rows"] += len(rows)

            if not rows:
                lines.append(f"-- Table public.{tbl}: 0 rows")
                continue

            lines.append(f"-- Data for public.{tbl} ({len(rows)} rows)")
            for row in rows:
                vals_sql = ", ".join(pg_literal(v) for v in row)
                lines.append(
                    f"INSERT INTO public.{quote_ident(tbl)} ({col_list_sql}) VALUES ({vals_sql});"
                )
            lines.append("")

        # ----------------------------------------------------------------------
        # 8. RESTORE EXACT SEQUENCE STATES (POST-DATA)
        # ----------------------------------------------------------------------
        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 8. SEQUENCE VALUE SYNCHRONIZATION (POST-DATA)",
            "-- --------------------------------------------------------------------------",
        ])
        for seq_name, last_val, is_called in all_seq_states:
            called_sql = "true" if is_called else "false"
            lines.append(
                f"SELECT pg_catalog.setval('public.{quote_ident(seq_name)}', {last_val}, {called_sql});"
            )
        lines.append("")

        # ----------------------------------------------------------------------
        # 9. CHECK CONSTRAINTS & FOREIGN KEYS (POST-DATA)
        # ----------------------------------------------------------------------
        checks = conn.execute(
            text("""
                SELECT c.relname AS table_name,
                       con.conname,
                       pg_get_constraintdef(con.oid, true) AS condef
                FROM pg_constraint con
                JOIN pg_class c ON c.oid = con.conrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'public'
                  AND con.contype = 'c'
                ORDER BY c.relname, con.conname;
            """)
        ).fetchall()

        fks = conn.execute(
            text("""
                SELECT c.relname AS table_name,
                       con.conname,
                       ref_n.nspname AS ref_schema,
                       ref_c.relname AS ref_table,
                       pg_get_constraintdef(con.oid, true) AS condef
                FROM pg_constraint con
                JOIN pg_class c ON c.oid = con.conrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                JOIN pg_class ref_c ON ref_c.oid = con.confrelid
                JOIN pg_namespace ref_n ON ref_n.oid = ref_c.relnamespace
                WHERE n.nspname = 'public'
                  AND con.contype = 'f'
                ORDER BY c.relname, con.conname;
            """)
        ).fetchall()

        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 9. CHECK CONSTRAINTS & FOREIGN KEYS (POST-DATA)",
            "-- --------------------------------------------------------------------------",
        ])
        for tbl_name, con_name, con_def in checks:
            lines.append(
                f"ALTER TABLE ONLY public.{quote_ident(tbl_name)} "
                f"ADD CONSTRAINT {quote_ident(con_name)} {con_def};"
            )
            manifest["constraints"]["total"] += 1
            manifest["constraints"]["check"] += 1

        for tbl_name, con_name, ref_schema, ref_table, con_def in fks:
            manifest["constraints"]["total"] += 1
            stmt = (
                f"ALTER TABLE ONLY public.{quote_ident(tbl_name)} "
                f"ADD CONSTRAINT {quote_ident(con_name)} {con_def};"
            )
            if ref_schema == "public":
                manifest["constraints"]["foreign_key_public"] += 1
                lines.append(stmt)
            else:
                manifest["constraints"]["foreign_key_external"] += 1
                escaped_stmt = stmt.replace("'", "''")
                lines.extend([
                    "DO $$ BEGIN",
                    f"    IF to_regclass('{ref_schema}.{ref_table}') IS NOT NULL THEN",
                    f"        EXECUTE '{escaped_stmt}';",
                    "    ELSE",
                    f"        RAISE NOTICE 'Skipping external-schema FK {con_name} because {ref_schema}.{ref_table} is absent on target DB.';",
                    "    END IF;",
                    "END $$;",
                ])
        lines.append("")

        # ----------------------------------------------------------------------
        # 10. INDEXES (STANDALONE & CONSTRAINT-BACKING SUMMARY)
        # ----------------------------------------------------------------------
        constraint_idx_count = conn.execute(
            text("""
                SELECT COUNT(*)
                FROM pg_indexes pi
                JOIN pg_class i ON i.relname = pi.indexname
                JOIN pg_namespace n ON n.oid = i.relnamespace AND n.nspname = pi.schemaname
                WHERE pi.schemaname = 'public'
                  AND EXISTS (SELECT 1 FROM pg_constraint con WHERE con.conindid = i.oid);
            """)
        ).scalar() or 0

        indexes = conn.execute(
            text("""
                SELECT t.relname AS table_name,
                       i.relname AS index_name,
                       pg_get_indexdef(ix.indexrelid) AS index_def
                FROM pg_class t
                JOIN pg_index ix ON t.oid = ix.indrelid
                JOIN pg_class i ON i.oid = ix.indexrelid
                JOIN pg_namespace n ON n.oid = t.relnamespace
                WHERE n.nspname = 'public'
                  AND NOT EXISTS (
                      SELECT 1 FROM pg_constraint con WHERE con.conindid = ix.indexrelid
                  )
                ORDER BY t.relname, i.relname;
            """)
        ).fetchall()

        manifest["indexes"]["constraint_backing"] = int(constraint_idx_count)
        manifest["indexes"]["standalone"] = len(indexes)
        manifest["indexes"]["total_pg_indexes"] = int(constraint_idx_count) + len(indexes)

        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 10. STANDALONE & PARTIAL INDEXES (CONSTRAINT INDEXES CREATED IN SECTION 5)",
            "-- --------------------------------------------------------------------------",
        ])
        for tbl_name, idx_name, idx_def in indexes:
            lines.append(f"{idx_def};")
        lines.append("")

        # ----------------------------------------------------------------------
        # 11. TRIGGERS
        # ----------------------------------------------------------------------
        triggers = conn.execute(
            text("""
                SELECT c.relname AS table_name,
                       t.tgname,
                       pg_get_triggerdef(t.oid) AS tgdef
                FROM pg_trigger t
                JOIN pg_class c ON c.oid = t.tgrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'public' AND NOT t.tgisinternal
                ORDER BY c.relname, t.tgname;
            """)
        ).fetchall()

        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 11. TRIGGERS (PUBLIC SCHEMA)",
            f"-- Note: External schema triggers calling public functions: {manifest['triggers']['external_schema_referencing_public']}",
            "-- --------------------------------------------------------------------------",
        ])
        for tbl_name, tg_name, tg_def in triggers:
            lines.append(f"{tg_def};")
            manifest["triggers"]["public_schema"] += 1
        lines.append("")

        # ----------------------------------------------------------------------
        # 12. ROW LEVEL SECURITY & POLICIES
        # ----------------------------------------------------------------------
        rls_tables = conn.execute(
            text("""
                SELECT c.relname, c.relrowsecurity, c.relforcerowsecurity
                FROM pg_class c
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = 'public' AND c.relkind = 'r'
                ORDER BY c.relname;
            """)
        ).fetchall()

        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 12. ROW LEVEL SECURITY & POLICIES",
            "-- --------------------------------------------------------------------------",
        ])
        for tbl_name, rls_enabled, rls_forced in rls_tables:
            if rls_enabled:
                lines.append(f"ALTER TABLE public.{quote_ident(tbl_name)} ENABLE ROW LEVEL SECURITY;")
            if rls_forced:
                lines.append(f"ALTER TABLE public.{quote_ident(tbl_name)} FORCE ROW LEVEL SECURITY;")

        policies = conn.execute(
            text("""
                SELECT tablename, policyname, permissive, roles::text[], cmd, qual, with_check
                FROM pg_policies
                WHERE schemaname = 'public'
                ORDER BY tablename, policyname;
            """)
        ).fetchall()

        lines.append("")
        for tbl_name, pol_name, permissive, roles_arr, cmd, qual, with_check in policies:
            manifest["policies"]["total"] += 1
            perm_sql = "AS PERMISSIVE" if permissive == "PERMISSIVE" else "AS RESTRICTIVE"
            roles_list = [r for r in (roles_arr or [])]
            roles_sql = ", ".join(quote_ident(r) for r in roles_list) if roles_list else "PUBLIC"
            parts = [
                f"CREATE POLICY {quote_ident(pol_name)} ON public.{quote_ident(tbl_name)}",
                perm_sql,
                f"FOR {cmd}",
                f"TO {roles_sql}",
            ]
            if qual is not None:
                parts.append(f"USING ({qual})")
            if with_check is not None:
                parts.append(f"WITH CHECK ({with_check})")
            pol_stmt = " ".join(parts) + ";"
            escaped_pol = pol_stmt.replace("'", "''")

            needs_auth = ("auth." in (qual or "")) or ("auth." in (with_check or ""))
            if needs_auth:
                manifest["policies"]["auth_dependent_guarded"] += 1
            else:
                manifest["policies"]["non_auth"] += 1

            role_checks = " AND ".join(
                f"EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{r}')"
                for r in roles_list
                if r.upper() != "PUBLIC"
            ) or "TRUE"

            cond = role_checks
            if needs_auth:
                cond = f"to_regproc('auth.uid()') IS NOT NULL AND {role_checks}"

            lines.extend([
                "DO $$ BEGIN",
                f"    IF {cond} THEN",
                f"        EXECUTE '{escaped_pol}';",
                "    ELSE",
                f"        RAISE NOTICE 'Skipping platform-specific RLS policy {pol_name} on public.{tbl_name} (requires missing role or Supabase auth.uid()).';",
                "    END IF;",
                "END $$;",
            ])
        lines.append("")

        # ----------------------------------------------------------------------
        # 13. SCHEMA, FUNCTION, TABLE & SEQUENCE ACL GRANTS
        # ----------------------------------------------------------------------
        lines.extend([
            "-- --------------------------------------------------------------------------",
            "-- 13. PRIVILEGES & ACL GRANTS (SCHEMA, FUNCTIONS, TABLES, SEQUENCES)",
            "-- --------------------------------------------------------------------------",
            "DO $$ BEGIN",
            "    REVOKE CREATE ON SCHEMA public FROM PUBLIC;",
            "    GRANT USAGE ON SCHEMA public TO PUBLIC;",
            "EXCEPTION WHEN insufficient_privilege THEN",
            "    RAISE NOTICE 'Skipping schema ACL hardening (insufficient privilege).';",
            "END $$;",
        ])

        schema_grants = conn.execute(
            text("""
                SELECT acl.grantee::regrole::text AS grantee,
                       string_agg(acl.privilege_type, ', ' ORDER BY acl.privilege_type) AS privs
                FROM pg_namespace n
                CROSS JOIN LATERAL aclexplode(n.nspacl) AS acl
                WHERE n.nspname = 'public'
                  AND acl.grantee <> 0
                  AND acl.grantee::regrole::text NOT IN ('pg_database_owner')
                GROUP BY 1
                ORDER BY 1;
            """)
        ).fetchall()
        for grantee, privs in schema_grants:
            stmt = f"GRANT {privs} ON SCHEMA public TO {quote_ident(grantee)};"
            escaped_stmt = stmt.replace("'", "''")
            lines.append(
                f"DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{grantee}') THEN EXECUTE '{escaped_stmt}'; END IF; END $$;"
            )

        lines.append("")
        # Function ACLs (CRITICAL: revokes default PUBLIC EXECUTE on non-PUBLIC functions)
        for fname, fn_args, _, has_acl, public_has_exec in funcs:
            fn_sig = f"public.{quote_ident(fname)}({fn_args})"
            if has_acl and not public_has_exec:
                manifest["functions"]["revoked_from_public"] += 1
                lines.append(f"REVOKE ALL ON FUNCTION {fn_sig} FROM PUBLIC;")

            fn_grants = conn.execute(
                text("""
                    SELECT acl.grantee::regrole::text AS grantee,
                           string_agg(acl.privilege_type, ', ' ORDER BY acl.privilege_type) AS privs
                    FROM pg_proc p
                    JOIN pg_namespace n ON n.oid = p.pronamespace
                    CROSS JOIN LATERAL aclexplode(p.proacl) AS acl
                    WHERE n.nspname = 'public'
                      AND p.proname = :fname
                      AND pg_catalog.pg_get_function_identity_arguments(p.oid) = :fn_args
                      AND acl.grantee <> 0
                      AND acl.grantee::regrole::text <> 'postgres'
                    GROUP BY 1
                    ORDER BY 1;
                """),
                {"fname": fname, "fn_args": fn_args},
            ).fetchall()
            for grantee, privs in fn_grants:
                stmt = f"GRANT {privs} ON FUNCTION {fn_sig} TO {quote_ident(grantee)};"
                escaped_stmt = stmt.replace("'", "''")
                lines.append(
                    f"DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{grantee}') THEN EXECUTE '{escaped_stmt}'; END IF; END $$;"
                )

        lines.append("")
        # Table ACLs using native aclexplode(relacl) to capture all PG17 privs (incl. MAINTAIN)
        for tbl in ordered_tables:
            lines.append(f"REVOKE ALL ON TABLE public.{quote_ident(tbl)} FROM PUBLIC;")
            grants = conn.execute(
                text("""
                    SELECT acl.grantee::regrole::text AS grantee,
                           string_agg(acl.privilege_type, ', ' ORDER BY acl.privilege_type) AS privs
                    FROM pg_class c
                    JOIN pg_namespace n ON n.oid = c.relnamespace
                    CROSS JOIN LATERAL aclexplode(c.relacl) AS acl
                    WHERE n.nspname = 'public'
                      AND c.relname = :t
                      AND c.relkind = 'r'
                      AND acl.grantee <> 0
                      AND acl.grantee::regrole::text <> 'postgres'
                    GROUP BY 1
                    ORDER BY 1;
                """),
                {"t": tbl},
            ).fetchall()
            for grantee, privs in grants:
                stmt = f"GRANT {privs} ON TABLE public.{quote_ident(tbl)} TO {quote_ident(grantee)};"
                escaped_stmt = stmt.replace("'", "''")
                lines.append(
                    f"DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{grantee}') THEN EXECUTE '{escaped_stmt}'; END IF; END $$;"
                )

        lines.append("")
        for seq_name, _, _ in all_seq_states:
            lines.append(f"REVOKE ALL ON SEQUENCE public.{quote_ident(seq_name)} FROM PUBLIC;")
            seq_grants = conn.execute(
                text("""
                    SELECT acl.grantee::regrole::text AS grantee,
                           string_agg(acl.privilege_type, ', ' ORDER BY acl.privilege_type) AS privs
                    FROM pg_class c
                    JOIN pg_namespace n ON n.oid = c.relnamespace
                    CROSS JOIN LATERAL aclexplode(c.relacl) AS acl
                    WHERE n.nspname = 'public'
                      AND c.relname = :s
                      AND c.relkind = 'S'
                      AND acl.grantee <> 0
                      AND acl.grantee::regrole::text <> 'postgres'
                    GROUP BY 1
                    ORDER BY 1;
                """),
                {"s": seq_name},
            ).fetchall()
            for grantee, privs in seq_grants:
                stmt = f"GRANT {privs} ON SEQUENCE public.{quote_ident(seq_name)} TO {quote_ident(grantee)};"
                escaped_stmt = stmt.replace("'", "''")
                lines.append(
                    f"DO $$ BEGIN IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{grantee}') THEN EXECUTE '{escaped_stmt}'; END IF; END $$;"
                )

    lines.extend(["", "COMMIT;", "", "-- End of Complete AutoInspect AI Logical PostgreSQL SQL Export", ""])

